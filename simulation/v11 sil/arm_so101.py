def _look_axes(pos, look, up_hint=(0.0, 1.0, 0.0)) -> str:
    """MuJoCo camera xyaxes (in its parent's frame) for a camera at pos looking at look."""
    z = np.asarray(pos, float) - np.asarray(look, float)
    z /= np.linalg.norm(z)
    x = np.asarray(up_hint, float) - (np.asarray(up_hint, float) @ z) * z
    x /= np.linalg.norm(x)
    y = np.cross(z, x)
    return _f(*x, *y)


