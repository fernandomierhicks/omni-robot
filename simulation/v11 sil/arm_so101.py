def bin_xml(p, plate_top: float) -> str:
    """params.arm_bin: an open box on the plate (structure: loose objects land in it), 3 mm walls, the display behind
    it (structure too: it backs the bin, a toy dropped long bounces off it)."""
    if p.arm_bin is None:
        return ""
    x, y, L, W, H = p.arm_bin
    t, z0 = 0.0015, plate_top
    walls = [((0, 0, t), (L / 2, W / 2, t)),
             ((L / 2 - t, 0, H / 2), (t, W / 2, H / 2)), ((-L / 2 + t, 0, H / 2), (t, W / 2, H / 2)),
             ((0, W / 2 - t, H / 2), (L / 2, t, H / 2)), ((0, -W / 2 + t, H / 2), (L / 2, t, H / 2))]
    rear = "".join(f'<geom name="{nm}" class="structure" type="box" size="{_f((dx1 - dx0) / 2, (dy1 - dy0) / 2, (dz1 - dz0) / 2)}" '
                   f'pos="{_f((dx0 + dx1) / 2, (dy0 + dy1) / 2, (dz0 + dz1) / 2)}" material="camera_body" mass="0"/>'
                   for nm, (dx0, dx1), (dy0, dy1), (dz0, dz1) in rear_boxes(p, plate_top))
