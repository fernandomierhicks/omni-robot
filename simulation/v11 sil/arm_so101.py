def _get(url: str, timeout: float = 60) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": "omni-robot-sim/1.0 (arm_so101.py)"})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return r.read()


def fetch(force: bool = False):
    """Download the SO-101's visual meshes (binary STL) at the pinned commit into assets/so101/ and write SOURCES.md."""
    ARM_DIR.mkdir(parents=True, exist_ok=True)
    rows = []
    for m in MESHES:
        f = ARM_DIR / f"{m}.stl"
        url = f"{REPO_RAW}/{COMMIT}/Simulation/SO101/assets/{m}.stl"
        if force or not f.exists():
            data = _get(url)
            n = int.from_bytes(data[80:84], "little") if len(data) >= 84 else -1
            if len(data) != 84 + 50 * n:
                raise RuntimeError(f"{m}: not a binary STL ({len(data)} bytes)")
            f.write_bytes(data)
            print(f"  {m}.stl ({len(data) // 1024} KB)")
        rows.append((m, url, hashlib.sha256(f.read_bytes()).hexdigest()[:16]))
    lines = ["# SO-101 meshes", "",
             f"Fetched by `python arm_so101.py fetch` (simulation/v11 sil) from TheRobotStudio/SO-ARM100 at commit "
             f"{COMMIT}, Simulation/SO101/assets. Licence Apache-2.0 (github.com/TheRobotStudio/SO-ARM100/blob/main/"
             "LICENSE). Visual only.", "", "| Mesh | URL | sha256 (16) |", "| --- | --- | --- |"]
    lines += [f"| {m} | {u} | {h} |" for m, u, h in rows]
    (ARM_DIR / "SOURCES.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    if sys.argv[1:2] == ["fetch"]:
        fetch(force="--force" in sys.argv)
    else:
        print("usage: python arm_so101.py fetch [--force]")
