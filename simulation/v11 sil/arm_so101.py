def gap_at(q: float) -> float:
    """Gap between the finger pads' inner faces near the tips (m) at gripper angle q (rad)."""
    (cx, cy, _), (hx, _, _) = MOVING_PAD
    x, y = cx - hx, cy                           # the moving pad's inner face, jaw frame
    xr = x * math.cos(q) - y * math.sin(q)
    return JAW_HINGE[0] + xr - (FIXED_PAD[0][0] + FIXED_PAD[1][0])


def q_for_gap(gap: float) -> float:
    """The gripper angle that leaves this gap between the pads (bisection; clipped to the joint's range)."""
    lo, hi = GRIPPER_CLOSED, 1.6
    if gap <= gap_at(lo):
        return lo
    for _ in range(40):
        mid = 0.5 * (lo + hi)
        lo, hi = (mid, hi) if gap_at(mid) < gap else (lo, mid)
    return 0.5 * (lo + hi)

