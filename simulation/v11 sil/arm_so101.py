class ArmServos:
    """The six STS3215s: each goal slewed at the no-load speed, the torque limit falling with speed (stall at rest,
    zero at the no-load speed) in the direction the joint moves; full stall torque against the motion."""

    def __init__(self, model, data, pose="stow"):
        self.m, self.d = model, data
        self.a = np.array([model.actuator(name(j)).id for j in JOINTS])
        self.qadr = np.array([model.joint(name(j)).qposadr[0] for j in JOINTS])
        self.vadr = np.array([model.joint(name(j)).dofadr[0] for j in JOINTS])
        self.lo, self.hi = joint_ranges().T
        self.speed = np.full(len(JOINTS), SERVO_SPEED)     # per-joint slew (a study may slow it)
        self.torque_scale = np.ones(len(JOINTS))           # the servos' torque limit (arm_bus: 0 = torque off)
        self.set_pose(POSES[pose] if isinstance(pose, str) else pose, snap=True)

    def set_pose(self, q, snap: bool = False):
        """New goal; snap = also put the joints there now (before a run starts)."""
        self.target = np.clip(np.asarray(q, dtype=float), self.lo, self.hi)
        if snap:
            self.cmd = self.target.copy()
            self.d.qpos[self.qadr] = self.cmd
            self.d.qvel[self.vadr] = 0.0
        elif not hasattr(self, "cmd"):
            self.cmd = self.d.qpos[self.qadr].copy()

    def q(self) -> np.ndarray:
        return self.d.qpos[self.qadr].copy()

    def settled(self, tol=math.radians(1.0)) -> bool:
        return bool(np.all(self.cmd == self.target) and np.all(np.abs(self.q() - self.target) < tol))

    def step(self, dt: float):
        step = self.speed * dt
        self.cmd += np.clip(self.target - self.cmd, -step, step)
        self.d.ctrl[self.a] = self.cmd
        w = self.d.qvel[self.vadr]
        frac = np.clip(1.0 - np.abs(w) / SERVO_SPEED, 0.0, 1.0)
        stall = SERVO_STALL * self.torque_scale
        up = np.where(w > 0, stall * frac, stall)
        down = np.where(w < 0, stall * frac, stall)
        self.m.actuator_forcerange[self.a, 0] = -down
        self.m.actuator_forcerange[self.a, 1] = up

    def bus_current(self, v_bus: float) -> float:
        """Pack current of the 12 V rail (DC-DC 90%): idle plus a share of the stall current by torque."""
        tau = np.abs(self.d.actuator_force[self.a])
        i = np.sum(SERVO_I_IDLE + (SERVO_I_STALL - SERVO_I_IDLE) * np.minimum(1.0, tau / SERVO_STALL))
        return float(i) * SERVO_V / v_bus / 0.9


