def meshes_available() -> bool:
    return all((ARM_DIR / f"{m}.stl").exists() for m in MESHES)


def _f(*v) -> str:
    return " ".join(f"{x:.6g}" for x in v)


def _link_capsules(body: ET.Element, pick: bool = False) -> list:
    """A capsule from each link's origin to its child link's origin (the tool point for the gripper). pick: the
    gripper's and the jaw's stop at the fingers' roots (the pads and FINGERTIPS stand for the fingers)."""
    out = []
    ends = [np.array([float(x) for x in c.get("pos").split()]) for c in body.findall("body")]
    if body.get("name") == "gripper":
        ends = [np.array([-0.0079, 0.0, -0.060]) if pick else
                np.array([float(x) for x in body.find("site").get("pos").split()])]
    if body.get("name") == "moving_jaw_so101_v1":
        ends = [np.array([0.0, -0.040 if pick else -0.065, 0.019])]   # the jaw's tip (est from its inertial: -0.030 along y)
    for e in ends:
        if np.linalg.norm(e) > 1e-3:
            out.append(e)
    return out


